// Small RFC 4180 style CSV parser: handles quoted fields, escaped quotes ("")
// and commas or newlines inside quotes. Returns an array of row objects keyed
// by the header row, with values trimmed.
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        inQuotes = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += ch;
    }
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }

  const [header, ...body] = rows.filter((r) => r.some((v) => v.trim() !== ""));
  const keys = header.map((h) => h.replace(/^﻿/, "").trim());
  return body.map((r) =>
    Object.fromEntries(keys.map((k, i) => [k, (r[i] ?? "").trim()]))
  );
}
